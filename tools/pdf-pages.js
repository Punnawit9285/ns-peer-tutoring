/* node tools/pdf-pages.js <student-pdftext.txt>
   Maps every section intro, concept card, and question in CVS.sections to its exact page
   number in the student handout PDF (ns1-anatomy-physiology-physics-ac-based-learning.pdf),
   writing src/pdf-pages.js (window.PDF_PAGES). */
const fs = require('fs');
global.window = global;
JSON.parse(fs.readFileSync('data/sections.json', 'utf8')).forEach(f => eval(fs.readFileSync('data/' + f + '.js', 'utf8')));

const txtFile = process.argv[2];
if (!txtFile) { console.error('usage: node tools/pdf-pages.js <pdftext.txt>'); process.exit(1); }

const lines = fs.readFileSync(txtFile, 'utf8').split('\n').filter(Boolean).map(l => {
  const i = l.indexOf('\t');
  return { n: +l.slice(0, i), t: l.slice(i + 1) };
});
const total = lines.length;
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const phrase = (str, from, to) => {
  const k = str.replace(/\s+/g, '');
  const p = lines.find(l => l.n >= (from || 1) && (!to || l.n <= to) && l.t.replace(/\s+/g, '').includes(k));
  return p ? p.n : 0;
};
const firstRe = (re, from, to) => {
  const p = lines.find(l => l.n >= (from || 1) && (!to || l.n <= to) && re.test(l.t));
  return p ? p.n : 0;
};

/* Answer key starts where quiz body ends — never match question IDs inside the answer key */
const ansStart = phrase('Answer key', 2) || total + 1;
const bodyEnd = ansStart - 1;

const secPages = {};
const cardPages = {};
const missing = [];

/* First pass: locate every concept page in body (pages 2..bodyEnd) */
const concepts = [];
CVS.sections.forEach(s => {
  s.items.forEach((it, idx) => {
    if (it.t === 'c') concepts.push({ s, it, idx });
  });
});

let cursor = 2;
concepts.forEach(c => {
  const re = new RegExp('(^|[^\\w-])' + esc(c.it.id) + '(?![\\w-])');
  /* Match concept header specifically (either "<id> Concept" or first occurrence at/after cursor) */
  let pg = phrase(c.it.id + 'Concept', cursor, bodyEnd);
  if (!pg) pg = firstRe(re, cursor, bodyEnd);
  if (!pg) pg = firstRe(re, 2, bodyEnd);
  if (!pg) missing.push(c.it.id);
  cardPages[c.it.id] = pg;
  if (pg && pg > cursor) cursor = pg;
});

/* Map every section to its first concept page (matches PDF TOC "STARTS" column) */
CVS.sections.forEach(s => {
  const firstC = s.items.find(it => it.t === 'c');
  secPages[s.id] = firstC ? cardPages[firstC.id] : 0;
  if (!secPages[s.id]) missing.push('sec-' + s.id);
});

/* Second pass: locate every question within its parent concept's quiz span */
for (let ci = 0; ci < concepts.length; ci++) {
  const { s, it: concept, idx } = concepts[ci];
  const nextInSec = s.items.slice(idx + 1).findIndex(x => x.t === 'c');
  const qs = nextInSec < 0 ? s.items.slice(idx + 1) : s.items.slice(idx + 1, idx + 1 + nextInSec);
  if (!qs.length) continue;

  const cPage = cardPages[concept.id] || 2;
  const nextC = concepts[ci + 1];
  const spanEnd = nextC && cardPages[nextC.it.id] ? Math.max(cPage, cardPages[nextC.it.id]) : bodyEnd;
  const quizStart = phrase('Quiz · ' + concept.id + ' ·', cPage, spanEnd) || cPage;

  let qCursor = quizStart;
  qs.forEach(q => {
    const re = new RegExp('(^|[^\\w-])' + esc(q.id) + '(?![\\w-])');
    let pg = firstRe(re, qCursor, spanEnd);
    if (!pg) pg = firstRe(re, quizStart, spanEnd);
    if (!pg) pg = quizStart; // fallback to its concept quiz page if PDF text broke the ID
    cardPages[q.id] = pg;
    if (pg > qCursor) qCursor = pg;
  });
}

if (missing.length) {
  console.error('Missing PDF pages for:', missing.join(', '));
  process.exit(1);
}

const payload = {
  file: 'ns1-anatomy-physiology-physics-ac-based-learning.pdf',
  total,
  sec: secPages,
  card: cardPages
};
const out = '/* Generated by tools/pdf-pages.js from ns1-anatomy-physiology-physics-ac-based-learning.pdf (' + total + ' pages). */\nwindow.PDF_PAGES = ' + JSON.stringify(payload) + ';\n';
fs.writeFileSync('src/pdf-pages.js', out);
console.log('Wrote src/pdf-pages.js:', Object.keys(secPages).length, 'sections,', Object.keys(cardPages).length, 'cards across', total, 'PDF pages (body ends p.' + bodyEnd + ', answers start p.' + ansStart + ')');
